"""Render selected layers directly from PrusaSlicer's relative-E G-code."""
from collections import Counter, defaultdict
import json
from pathlib import Path
import re
import sys
from math import dist

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
PATTERN = re.compile(r"([XYE])([-+]?(?:[0-9]*\.)?[0-9]+)")
ROLES = {
    "External perimeter": "#ddbc76", "Perimeter": "#735b6b",
    "Solid infill": "#488e96", "Top solid infill": "#74bdb1",
    "Internal infill": "#3a4462", "Bridge infill": "#ff9f64",
    "Overhang perimeter": "#d75471",
}


def read(file):
    by_z = defaultdict(list)
    cfg = {}
    xy = [0., 0.]
    z = 0.
    feature = ""
    header = []
    with file.open() as stream:
        for line in stream:
            if line.startswith("; generated by "):
                header = re.search(r"PrusaSlicer [\d.]+", line)[0]
            elif line.startswith(";Z:"):
                z = float(line[3:])
            elif line.startswith(";TYPE:"):
                feature = line[6:].strip()
            elif line.startswith(("G1 ", "G0 ")):
                words = dict((k, float(v)) for k, v in PATTERN.findall(line))
                endpoint = [words.get(axis, xy[i]) for i, axis in enumerate("XY")]
                if feature and z and words.get("E", 0) > 0 and endpoint != xy:
                    by_z[z].append((feature, tuple(xy), tuple(endpoint)))
                xy = endpoint
            elif line.startswith("; ") and " = " in line:
                key, value = line[2:].rstrip("\n").split(" = ", 1)
                cfg[key] = value
    return by_z, cfg, header


def draw_layer(im, paths, at, title, z, font, small):
    dr = ImageDraw.Draw(im)
    ox, oy = at
    dr.rounded_rectangle((ox, oy, ox+604, oy+306), radius=13, fill="#1c2230")
    dr.text((ox+18, oy+14), title, font=font, fill="#f0d296")
    dr.text((ox+19, oy+44), f"Z = {z:.2f} mm", font=small, fill="#b1bbcf")
    scale = 2.12

    def xy(p):
        return ox+41+(p[0]-55)*scale, oy+69+(225-p[1])*scale

    for feature, start, end in paths:
        if feature in ROLES:
            dr.line([xy(start), xy(end)], width=2 if feature != "Internal infill" else 1,
                    fill=ROLES[feature])


def main():
    by_z, cfg, header = read(Path(sys.argv[1]))
    assert len(by_z) > 50 and cfg["nozzle_diameter"] == "0.25"
    assert cfg["layer_height"] == "0.08"
    counts = Counter(role for moves in by_z.values() for role, _, _ in moves)
    first = min(by_z)
    max_z = max(by_z)
    first_counts = [sum(role == "External perimeter" and (end[0]>175)==right
                        for role, _, end in by_z[first])
                    for right in (False, True)]
    assert min(first_counts) > 80, first_counts
    assert not any("Support" in role for role in counts)
    bridges = [(dist(start, end), z, start, end) for z, layer in by_z.items()
               for role, start, end in layer if role == "Bridge infill"]
    assert bridges
    assert max(bridges)[0] < 8.5, "Unexpected bridge beyond the stock pocket scale"
    def run_lengths(layer):
        last = None
        length = 0.
        for role, a, b in layer:
            if role != "Bridge infill" or (last is not None and dist(a, last) > .004):
                if length:
                    yield length
                length = 0.
            if role == "Bridge infill":
                length += dist(a, b)
                last = b
            else:
                last = None
        if length:
            yield length

    bridge_length, bridge_z = max((length, z) for z, layer in by_z.items()
                                  for length in run_lengths(layer))
    max_segment, max_segment_z, a, b = max(bridges)
    print("Max straight bridge", max_segment, max_segment_z, a, b)
    print("Longest contiguous bridging path", bridge_length, bridge_z)
    img = Image.new("RGB", (1256, 778), "#131925")
    title = ImageFont.truetype("C:/Windows/Fonts/georgia.ttf", 31)
    font = ImageFont.truetype("C:/Windows/Fonts/segoeui.ttf", 19)
    small = ImageFont.truetype("C:/Windows/Fonts/segoeui.ttf", 16)
    dr = ImageDraw.Draw(img)
    dr.text((20, 13), "Mulan NX3  /  Actual slice", font=title, fill="#efd5a0")
    dr.text((22, 57), f'{header}  /  {cfg["nozzle_diameter"]} mm nozzle  /  {cfg["layer_height"]} mm layers', font=small,
            fill="#aab6cc")
    mid = min(by_z, key=lambda h: abs(h-3.73))
    near_top = min(by_z, key=lambda h: abs(h-9.59))
    layers = [("First-layer contact", first), ("Largest bridge layer", max_segment_z),
              ("Foreground and dragon relief", mid), ("Coin border — raised keys and edge rails", near_top)]
    for i, (label, z) in enumerate(layers):
        draw_layer(img, by_z[z], (18+(i%2)*616, 91+(i//2)*315), label, z, font, small)
    for i, (role, color) in enumerate(ROLES.items()):
        x = 25 + i*174
        dr.line([(x, 748), (x+18, 748)], fill=color, width=3)
        dr.text((x+23, 736), role, font=small, fill="#d6d9e1")
    img.save(ROOT / "previews/slicer_layers_025mm.png")
    report = {
        "status": "PASS",
        "slicer": header,
        "project": "Mulan_NX3_Voron24_025mm_45deg.3mf",
        "config": {k: cfg[k] for k in [
            "printer_settings_id", "filament_settings_id", "nozzle_diameter",
            "layer_height", "first_layer_height", "bed_shape", "temperature",
            "first_layer_temperature", "bed_temperature", "first_layer_bed_temperature",
            "gcode_flavor", "seam_position", "brim_width", "support_material",
            "resolution", "slice_closing_radius", "nozzle_high_flow",
            "min_layer_height", "max_layer_height", "bridge_speed", "bridge_flow_ratio"]},
        "part_count": 2, "bed_rotation_deg": 45,
        "first_layer_external_extrusion_moves_left_right": first_counts,
        "max_toolpath_z_mm": max_z,
        "support_extrusion_moves": 0,
        "longest_straight_bridge_move_mm": round(max_segment, 2),
        "longest_straight_bridge_z_mm": max_segment_z,
        "longest_straight_bridge_midpoint_mm": [round((x+y)/2, 2) for x,y in zip(a,b)],
        "longest_contiguous_bridge_path_mm": round(bridge_length, 2),
        "longest_contiguous_bridge_z_mm": bridge_z,
        "estimated_print_time": cfg["estimated printing time (normal mode)"],
        "estimated_filament_g": float(cfg["total filament used [g]"]),
        "viewed_z_mm": [z for _, z in layers], "physical_fit": "Pending",
    }
    (ROOT / "slicer_preflight.json").write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
